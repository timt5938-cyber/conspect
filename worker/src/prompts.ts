export const CONSPECT_SCHEMA_INSTRUCTION = `Структура ответа задана JSON-схемой. Заполняй её строго по смыслу.

Поля:
- title: короткое название темы БЕЗ слова "Тема:" (например "Транзакции в реляционных СУБД").
- subject: учебная дисциплина, если её можно уверенно определить из материала. Иначе пустая строка.
- summary: 1-2 предложения — о чём этот конспект.
- sections: 2-7 смысловых блоков. Порядок — логика изложения, а не порядок абзацев во входе.
  - heading: короткий заголовок блока. Формат нумерации внутри heading не нужен: "Архитектура клиент-сервер", а не "1. Архитектура".
  - lines: строки конспекта. У каждой строки есть kind:
    - "bullet"   — обычный тезис, факт, элемент списка.
    - "text"     — связное пояснение в 1-3 строках, когда список неуместен.
    - "definition" — определение термина. Пиши в виде "Термин — определение."
    - "formula"  — формула, закон, команда или код. Только сама запись, без пояснений.
    - "important" — то, что преподаватель требует знать: правило, условие, исключение.
    - "conclusion" — итог раздела или всей темы.
  - Длина строки: не больше ~80 символов. Длинную мысль разбивай на несколько строк, а не пиши монолит.
- key_terms: 3-8 ключевых терминов темы (только сами термины).
- questions: 2-5 вопросов для самопроверки по теме.

Правила содержания:
- Убирай "воду", вступления лектора, повторы, междометия, обращения к аудитории.
- Сохраняй ПОЛНОТУ: ни одно определение, формула и классификация из входа не должны потеряться.
- Формулы, индексы и обозначения оставляй в читаемой текстовой записи (E = m * c^2, a[i], x -> y).
- Язык конспекта — тот же, что у входа (обычно русский).`;

